//! Formatted Excel export of a takeoff: Summary (per group, with live cost
//! formulas and totals), By sheet, and Items. Pure Rust, testable anywhere.

use std::path::Path;

use rust_xlsxwriter::{Color, Format, FormatAlign, FormatBorder, Formula, Workbook, Worksheet, XlsxError};

use crate::takeoff::{fmt_qty, fmt_slope, Qty, Takeoff, Totals, Units};

struct Formats {
    title: Format,
    header: Format,
    text: Format,
    num: Format,
    int: Format,
    money: Format,
    total_label: Format,
    total_num: Format,
    total_int: Format,
    total_money: Format,
    note: Format,
}

fn formats() -> Formats {
    let header = Format::new()
        .set_bold()
        .set_font_color(Color::White)
        .set_background_color(Color::RGB(0xC62828))
        .set_align(FormatAlign::Center)
        .set_text_wrap()
        .set_border(FormatBorder::Thin);
    let total = Format::new().set_bold().set_border_top(FormatBorder::Double).set_background_color(Color::RGB(0xF3F3F3));
    Formats {
        title: Format::new().set_bold().set_font_size(14),
        header,
        text: Format::new(),
        num: Format::new().set_num_format("#,##0.00"),
        int: Format::new().set_num_format("#,##0"),
        money: Format::new().set_num_format("$#,##0.00"),
        total_label: total.clone(),
        total_num: total.clone().set_num_format("#,##0.00"),
        total_int: total.clone().set_num_format("#,##0"),
        total_money: total.set_num_format("$#,##0.00"),
        note: Format::new().set_italic().set_font_color(Color::RGB(0x666666)),
    }
}

/// A1-style column letter (0 = A).
fn col(c: u16) -> String {
    let mut c = c as u32 + 1;
    let mut s = String::new();
    while c > 0 {
        let r = (c - 1) % 26;
        s.insert(0, (b'A' + r as u8) as char);
        c = (c - 1) / 26;
    }
    s
}

fn headers(ws: &mut Worksheet, row: u32, names: &[&str], f: &Formats) -> Result<(), XlsxError> {
    for (i, h) in names.iter().enumerate() {
        ws.write_string_with_format(row, i as u16, *h, &f.header)?;
    }
    ws.set_row_height(row, 30)?;
    Ok(())
}

pub fn write(t: &Takeoff, path: &Path, title: &str, sheet_name: &dyn Fn(u32) -> String) -> Result<(), XlsxError> {
    let f = formats();
    let u = t.export_units();
    let imperial = t.units != Units::Metric;
    let mut wb = Workbook::new();

    // ---------------------------------------------------------- Summary
    let ws = wb.add_worksheet();
    ws.set_name("Summary")?;
    ws.write_string_with_format(0, 0, format!("{title} \u{2014} takeoff summary"), &f.title)?;
    ws.write_string_with_format(
        1,
        0,
        "Visible layers only. Edit the unit prices (yellow) and the costs update. Generated by Red-Beam.",
        &f.note,
    )?;
    let h = [
        "Group".to_string(),
        format!("Length ({})", u.len_unit),
        format!("Area ({})", u.area_unit),
        format!("Perimeter ({})", u.len_unit),
        format!("Wall area ({})", u.area_unit),
        format!("Volume ({})", u.vol_unit),
        "Count (EA)".into(),
        "$ / LF".into(),
        "$ / SF".into(),
        "$ / CY".into(),
        "$ / EA".into(),
        "Cost".into(),
    ];
    let hr: Vec<&str> = h.iter().map(|s| s.as_str()).collect();
    headers(ws, 3, &hr, &f)?;
    let price = f.money.clone().set_background_color(Color::RGB(0xFFF8C5));
    let groups = t.group_totals();
    let first = 4u32;
    for (i, (g, tot)) in groups.iter().enumerate() {
        let r = first + i as u32;
        ws.write_string_with_format(r, 0, &g.name, &f.text)?;
        ws.write_number_with_format(r, 1, tot.len * u.len, &f.num)?;
        ws.write_number_with_format(r, 2, tot.area * u.area, &f.num)?;
        ws.write_number_with_format(r, 3, tot.perimeter * u.len, &f.num)?;
        ws.write_number_with_format(r, 4, tot.wall * u.area, &f.num)?;
        ws.write_number_with_format(r, 5, tot.vol * u.vol, &f.num)?;
        ws.write_number_with_format(r, 6, tot.count as f64, &f.int)?;
        let p = g.prices;
        for (c, v) in [(7u16, p.per_lf), (8, p.per_sf), (9, p.per_cy), (10, p.per_ea)] {
            match v {
                Some(v) => ws.write_number_with_format(r, c, v, &price)?,
                None => ws.write_blank(r, c, &price)?,
            };
        }
        // Cost = length x $/LF + (area + wall area) x $/SF + volume x $/CY
        // + count x $/EA. Prices are per imperial unit, so the live formula
        // is only used when quantities are imperial.
        let n = r + 1;
        if imperial {
            let formula = format!("=B{n}*H{n}+(C{n}+E{n})*I{n}+F{n}*J{n}+G{n}*K{n}");
            ws.write_formula_with_format(r, 11, Formula::new(formula).set_result(format!("{:.2}", tot.cost)), &f.money)?;
        } else {
            ws.write_number_with_format(r, 11, tot.cost, &f.money)?;
        }
    }
    let tr = first + groups.len() as u32;
    ws.write_string_with_format(tr, 0, "TOTAL", &f.total_label)?;
    let sum_all = |sel: &dyn Fn(&Totals) -> f64| groups.iter().map(|(_, t)| sel(t)).sum::<f64>();
    let cols: [(u16, f64, &Format); 7] = [
        (1, sum_all(&|t| t.len * u.len), &f.total_num),
        (2, sum_all(&|t| t.area * u.area), &f.total_num),
        (3, sum_all(&|t| t.perimeter * u.len), &f.total_num),
        (4, sum_all(&|t| t.wall * u.area), &f.total_num),
        (5, sum_all(&|t| t.vol * u.vol), &f.total_num),
        (6, sum_all(&|t| t.count as f64), &f.total_int),
        (11, sum_all(&|t| t.cost), &f.total_money),
    ];
    for c in 7..11 {
        ws.write_blank(tr, c, &f.total_label)?;
    }
    for (c, v, fmt) in cols {
        if groups.is_empty() {
            ws.write_number_with_format(tr, c, 0.0, fmt)?;
        } else {
            let l = col(c);
            let formula = format!("=SUM({l}{}:{l}{})", first + 1, tr);
            ws.write_formula_with_format(tr, c, Formula::new(formula).set_result(format!("{v:.2}")), fmt)?;
        }
    }
    ws.set_column_width(0, 28)?;
    for c in 1..=6 {
        ws.set_column_width(c, 13)?;
    }
    for c in 7..=10 {
        ws.set_column_width(c, 10)?;
    }
    ws.set_column_width(11, 15)?;
    ws.set_freeze_panes(4, 1)?;

    // --------------------------------------------------------- By sheet
    let ws = wb.add_worksheet();
    ws.set_name("By sheet")?;
    let h = [
        "Sheet".to_string(),
        "Group".into(),
        format!("Length ({})", u.len_unit),
        format!("Area ({})", u.area_unit),
        format!("Perimeter ({})", u.len_unit),
        format!("Wall area ({})", u.area_unit),
        format!("Volume ({})", u.vol_unit),
        "Count (EA)".into(),
        "Cost".into(),
    ];
    let hr: Vec<&str> = h.iter().map(|s| s.as_str()).collect();
    headers(ws, 0, &hr, &f)?;
    let rows = t.sheet_totals();
    for (i, ((sheet, group), tot)) in rows.iter().enumerate() {
        let r = 1 + i as u32;
        ws.write_string(r, 0, sheet_name(*sheet))?;
        ws.write_string(r, 1, group)?;
        for (c, v) in [(2u16, tot.len * u.len), (3, tot.area * u.area), (4, tot.perimeter * u.len), (5, tot.wall * u.area), (6, tot.vol * u.vol)] {
            ws.write_number_with_format(r, c, v, &f.num)?;
        }
        ws.write_number_with_format(r, 7, tot.count as f64, &f.int)?;
        if tot.priced {
            ws.write_number_with_format(r, 8, tot.cost, &f.money)?;
        }
    }
    if !rows.is_empty() {
        ws.autofilter(0, 0, rows.len() as u32, 8)?;
    }
    ws.set_column_width(0, 18)?;
    ws.set_column_width(1, 24)?;
    for c in 2..=8 {
        ws.set_column_width(c, 13)?;
    }
    ws.set_freeze_panes(1, 0)?;

    // ------------------------------------------------------------ Items
    let ws = wb.add_worksheet();
    ws.set_name("Items")?;
    let names = [
        "Group", "Layer", "Sheet", "Type", "Quantity", "Unit", "Perimeter", "Volume", "Wall area", "Depth", "Wall height", "Slope",
        "Cost", "Display", "Scale", "Counted",
    ];
    headers(ws, 0, &names, &f)?;
    let mut items: Vec<_> = t.items.iter().collect();
    items.sort_by(|a, b| (&a.group, a.sheet, a.id).cmp(&(&b.group, b.sheet, b.id)));
    for (i, m) in items.iter().enumerate() {
        let r = 1 + i as u32;
        let scale = t.scale(m.sheet);
        let q = m.qty(scale);
        ws.write_string(r, 0, &m.group)?;
        ws.write_string(r, 1, &m.layer)?;
        ws.write_string(r, 2, sheet_name(m.sheet))?;
        ws.write_string(r, 3, m.kind.name())?;
        match q {
            Qty::Length(l) => {
                ws.write_number_with_format(r, 4, l * u.len, &f.num)?;
                ws.write_string(r, 5, u.len_unit)?;
            }
            Qty::Area { area, perimeter, volume } => {
                ws.write_number_with_format(r, 4, area * u.area, &f.num)?;
                ws.write_string(r, 5, u.area_unit)?;
                ws.write_number_with_format(r, 6, perimeter * u.len, &f.num)?;
                if let Some(v) = volume {
                    ws.write_number_with_format(r, 7, v * u.vol, &f.num)?;
                }
            }
            Qty::Count(n) => {
                ws.write_number_with_format(r, 4, n as f64, &f.int)?;
                ws.write_string(r, 5, "EA")?;
            }
            Qty::Unscaled => {
                ws.write_string(r, 5, "no scale")?;
            }
        }
        if let Some(w) = m.wall_area(scale) {
            ws.write_number_with_format(r, 8, w * u.area, &f.num)?;
        }
        if let Some(d) = m.depth_in {
            ws.write_number_with_format(r, 9, d * u.len, &f.num)?;
        }
        if let Some(hgt) = m.height_in {
            ws.write_number_with_format(r, 10, hgt * u.len, &f.num)?;
        }
        if let Some(s) = m.slope {
            ws.write_string(r, 11, fmt_slope(s))?;
        }
        if let Some(c) = t.cost(m) {
            ws.write_number_with_format(r, 12, c, &f.money)?;
        }
        ws.write_string(r, 13, fmt_qty(q, t.units))?;
        ws.write_string(r, 14, scale.map(|s| s.label.as_str()).unwrap_or(""))?;
        ws.write_string(r, 15, if t.layer_visible(&m.layer) { "yes" } else { "no (hidden layer)" })?;
    }
    if !items.is_empty() {
        ws.autofilter(0, 0, items.len() as u32, 15)?;
    }
    for (c, w) in [(0u16, 24.0), (1, 14.0), (2, 16.0), (3, 10.0), (13, 26.0), (14, 16.0), (15, 16.0)] {
        ws.set_column_width(c, w)?;
    }
    for c in 4..=12 {
        ws.set_column_width(c, 12)?;
    }
    ws.set_freeze_panes(1, 0)?;

    wb.save(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::takeoff::{Kind, Prices, Scale};

    #[test]
    fn writes_workbook() {
        assert_eq!(col(0), "A");
        assert_eq!(col(11), "L");
        assert_eq!(col(26), "AA");
        let mut t = Takeoff::new();
        t.scales.insert(0, Scale::from_ratio("1/8\" = 1'-0\"", 96.0));
        t.add(0, Kind::Area, vec![[0.0, 0.0], [192.0, 0.0], [192.0, 96.0], [0.0, 96.0]], "Flooring", "Base");
        t.add(0, Kind::Count, vec![[1.0, 1.0], [2.0, 2.0]], "Flooring", "Base");
        t.groups[0].prices = Prices { per_sf: Some(4.5), per_ea: Some(12.0), ..Default::default() };
        let dir = std::env::temp_dir().join(format!("rb-xlsx-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let p = dir.join("t.xlsx");
        write(&t, &p, "A-101", &|i| format!("Sheet {}", i + 1)).unwrap();
        let bytes = std::fs::read(&p).unwrap();
        assert!(bytes.starts_with(b"PK"), "xlsx is a zip");
        let _ = std::fs::remove_dir_all(dir);
    }
}
